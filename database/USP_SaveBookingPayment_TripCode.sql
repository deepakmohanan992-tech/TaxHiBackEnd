/*
  USP_SaveBookingPayment: persist the TripCode generated by the API.

  Backward compatible: new trailing parameter @TripCode VARCHAR(10) = NULL. When omitted, behaviour is
  exactly as before (VehicleBookingMaster.VehicleTripCodeMasterId stays NULL). Everything else is unchanged.

  When supplied, inside the existing transaction (just before the VehicleBookingMaster insert) a row is added
  to dbo.VehicleTripCodeMaster and VehicleBookingMaster.VehicleTripCodeMasterId points at it, so a rollback
  discards the code with the booking. A code that already exists raises error 50007 and the API retries
  with a fresh code. Idempotent duplicate requests return the existing booking before any of this runs.
*/
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO


ALTER PROCEDURE [dbo].[USP_SaveBookingPayment]
    @ClientRequestId UNIQUEIDENTIFIER,
    @UserId INT,
    @BookingNo VARCHAR(50),
    @Name NVARCHAR(300),
    @PhoneNumber NVARCHAR(20),
    @Email NVARCHAR(320),
    @AlternateEmail NVARCHAR(320) = NULL,
    @HasGST BIT = 0,
    @GSTNumber NVARCHAR(15) = NULL,
    @GSTCompanyName NVARCHAR(200) = NULL,
    @TripType NVARCHAR(30),
    @FromCityId INT,
    @ToCityId INT,
    @Route NVARCHAR(500) = NULL,
    @PickupDateTime DATETIME2(0),
    @ReturnDateTime DATETIME2(0),
    @DropDate DATE = NULL,
    @PickupLocation NVARCHAR(500),
    @DropLocation NVARCHAR(500),
    @VendorId INT,
    @VehicleId INT,
    @VehicleDetailsId INT,
    @VehicleCategoryId INT,
    @VehicleBrandId INT,
    @VehicleName NVARCHAR(200),
    @FuelType NVARCHAR(30) = NULL,
    @PaymentOption NVARCHAR(20),
    @CouponCode NVARCHAR(50) = NULL,
    @DiscountAmount DECIMAL(18,2),
    @BaseFare DECIMAL(18,2),
    @DriverAllowance DECIMAL(18,2),
    @AddOnsTotalAmount DECIMAL(18,2),
    @GSTAmount DECIMAL(18,2),
    @TotalFare DECIMAL(18,2),
    @PayableNowAmount DECIMAL(18,2),
    @BalancePayableAmount DECIMAL(18,2),
    @AddOns XML = NULL,
    @HoldMinutes INT = 15,
    @LockTimeoutMs INT = 10000,
    @TripCode VARCHAR(10) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE
        @ExistingBookingId INT = NULL,
        @BookingId INT = NULL,
        @VehicleTripGuestMasterId INT,
        @VehicleTripMasterId INT,
        @VehicleBookingMasterId INT,
        @VendorName VARCHAR(50),
        @RegistrationNo VARCHAR(20),
        @Now DATETIME2(3) = SYSUTCDATETIME(),
        @ReqStart DATE,
        @ReqEnd DATE,
        @CalcTotal DECIMAL(18,2),
        @CalcPayNow DECIMAL(18,2);

    BEGIN TRY

        /*=========================================================
          1. VALIDATION
        =========================================================*/

        IF @ClientRequestId IS NULL
            THROW 50001, 'ClientRequestId is required.', 1;

        IF @ReturnDateTime IS NULL
            THROW 50002, 'ReturnDateTime is required.', 1;

        IF @PickupDateTime IS NULL
            THROW 50003, 'PickupDateTime is required.', 1;

        IF @ReturnDateTime < @PickupDateTime
            THROW 50004,
                'ReturnDateTime cannot be before PickupDateTime.',
                1;

        IF @HoldMinutes <= 0
            THROW 50005, 'HoldMinutes must be greater than zero.', 1;

        SET @ReqStart = CAST(@PickupDateTime AS DATE);

        SET @ReqEnd = ISNULL(
            @DropDate,
            @ReqStart
        );

        IF @ReqEnd < @ReqStart
            THROW 50006,
                'DropDate cannot be before the pickup date.',
                1;

        /*=========================================================
          2. FARE VALIDATION
        =========================================================*/

        SET @CalcTotal =
            ROUND(
                @BaseFare
                + @DriverAllowance
                + @AddOnsTotalAmount
                + @GSTAmount
                - @DiscountAmount,
                2
            );

        SET @CalcPayNow =
            CASE
                WHEN @PaymentOption = 'PartPay'
                    THEN ROUND(@CalcTotal * 25 / 100, 2)
                ELSE @CalcTotal
            END;

        IF @PaymentOption NOT IN ('PartPay', 'FullPay')
            OR @CalcTotal IS NULL
            OR @CalcPayNow IS NULL
            OR ABS(@CalcTotal - @TotalFare) > 0.01
            OR ABS(@CalcPayNow - @PayableNowAmount) > 0.01
            OR ABS(
                (@CalcTotal - @CalcPayNow)
                - @BalancePayableAmount
            ) > 0.01
        BEGIN
            THROW 50007,
                'Fare details do not match the calculated amounts.',
                1;
        END;

        /*=========================================================
          3. GET VENDOR AND VEHICLE INFORMATION
        =========================================================*/

        SELECT
            @VendorName = VendorName
        FROM dbo.TransportVendorMaster
        WHERE VendorId = @VendorId;

        SELECT
            @RegistrationNo = RegistrationNumber
        FROM dbo.TransportVendorVehilceDetails
        WHERE VehicleId = @VehicleId;

        /*=========================================================
          4. BEGIN TRANSACTION
        =========================================================*/

        BEGIN TRANSACTION;

        /*=========================================================
          5. IDEMPOTENCY CHECK
        =========================================================*/

        SELECT
            @ExistingBookingId = BookingId
        FROM dbo.TaxHiBEBookings
        WHERE ClientRequestId = @ClientRequestId;

        IF @ExistingBookingId IS NULL
        BEGIN

            /*=====================================================
              6. ACQUIRE VEHICLE LOCK
            =====================================================*/

            EXEC dbo.USP_AcquireVehicleBookingLock
                @VehicleDetailsId = @VehicleDetailsId,
                @LockTimeoutMs = @LockTimeoutMs;

            /* Recheck duplicate request after acquiring lock */

            SELECT
                @ExistingBookingId = BookingId
            FROM dbo.TaxHiBEBookings
            WHERE ClientRequestId = @ClientRequestId;

        END;

        /*=========================================================
          7. CHECK VEHICLE AVAILABILITY
        =========================================================*/

        IF @ExistingBookingId IS NULL
        BEGIN

            IF EXISTS
            (
                SELECT 1
                FROM dbo.VehicleTripMaster T
                WHERE T.VehicleDetailsId = @VehicleDetailsId
                  AND T.VendorId = @VendorId
                  AND T.VehicleTripStatusId IN (1, 2)
                  AND T.FromDate IS NOT NULL
                  AND T.FromDate <= @ReqEnd
                  AND ISNULL(T.ToDate, T.FromDate) >= @ReqStart
            )
            OR EXISTS
            (
                SELECT 1
                FROM dbo.TaxHiBEBookings B
                WHERE B.VehicleDetailsId = @VehicleDetailsId
                  AND B.VendorId = @VendorId
                  AND B.PickupDateTime IS NOT NULL
                  AND
                  (
                      B.BookingStatus = 'Confirmed'
                      OR
                      (
                          B.BookingStatus = 'Pending'
                          AND B.HoldExpiresAtUtc > @Now
                      )
                  )
                  AND CAST(B.PickupDateTime AS DATE) <= @ReqEnd
                  AND ISNULL(
                      B.DropDate,
                      CAST(B.PickupDateTime AS DATE)
                  ) >= @ReqStart
            )
            BEGIN
                THROW 50008,
                    'This vehicle has already been reserved for the selected date and time.',
                    1;
            END;

            /*=====================================================
              8. INSERT VEHICLE TRIP GUEST MASTER
            =====================================================*/

            INSERT INTO dbo.VehicleTripGuestMaster
            (
                GuestName,
                Mobile
            )
            VALUES
            (
                LEFT(@Name, 250),
                LEFT(@PhoneNumber, 20)
            );

            SET @VehicleTripGuestMasterId =
                CAST(SCOPE_IDENTITY() AS INT);

            /*=====================================================
              9. INSERT VEHICLE TRIP MASTER
            =====================================================*/

            INSERT INTO dbo.VehicleTripMaster
            (
                VendorId,
                FromDate,
                ToDate,
                NoOfDays,
                DriverId,
                DriverName,
                VehicleCategoryId,
                VehicleBrandId,
                VehicleDetailsId,
                RegistrationNo,
                CreatedByUserId,
                CreatedOn,
                VehicleTripStatusId,
                VehicleVendorName,
                DriverMobile,
                StartingCityId,
                EndingCityId
            )
            VALUES
            (
                @VendorId,
                @ReqStart,
                @ReqEnd,
                DATEDIFF(DAY, @ReqStart, @ReqEnd) + 1,
                0,
                '',
                @VehicleCategoryId,
                @VehicleBrandId,
                @VehicleDetailsId,
                ISNULL(@RegistrationNo, ''),
                @UserId,
                GETDATE(),
                0,
                @VendorName,
                '',
                @FromCityId,
                @ToCityId
            );

            SET @VehicleTripMasterId =
                CAST(SCOPE_IDENTITY() AS INT);

            /*=====================================================
              10. INSERT VEHICLE BOOKING MASTER
            =====================================================*/

            DECLARE @VehicleTripCodeMasterId INT = NULL;

            IF @TripCode IS NOT NULL
            BEGIN
                IF EXISTS (SELECT 1 FROM dbo.VehicleTripCodeMaster WHERE TripCode = @TripCode)
                    THROW 50007, 'TripCode already exists.', 1;

                INSERT INTO dbo.VehicleTripCodeMaster (TripCode) VALUES (@TripCode);

                SET @VehicleTripCodeMasterId = CAST(SCOPE_IDENTITY() AS INT);
            END;

            INSERT INTO dbo.VehicleBookingMaster
            (
                VehicleTripMasterId,
                VehicleTripGuestMasterId,
                FileHandlerIdOrName,
                AgentName,
                FlightOrTrainDetails,
                VehicleTripBookStatusId,
                PickUpFrom,
                IsMasterBooking,
                FileHandlerCode,
                ProgramName,
                StartDate,
                EndDate,
                CancellationRemark,
                TransportVendorAgentId,
                VehicleTripCodeMasterId,
                TransportVendorAgentFileHandlerId
            )
            VALUES
            (
                @VehicleTripMasterId,
                @VehicleTripGuestMasterId,
                '',
                '',
                '',
                1,
                LEFT(@PickupLocation, 150),
                1,
                '',
                '',
                @ReqStart,
                @ReqEnd,
                NULL,
                NULL,
                @VehicleTripCodeMasterId,
                NULL
            );

            SET @VehicleBookingMasterId =
                CAST(SCOPE_IDENTITY() AS INT);

            /*=====================================================
              11. INSERT VEHICLE BOOKING DETAILS
            =====================================================*/

            INSERT INTO dbo.VehicleBookingDetails
            (
                VehicleBookingMasterId,
                [Day],
                IsNoMovement,
                JourneyDate,
                PickUpCityId,
                DropCityId,
                PickUpCity,
                DropCity,
                VehicleTimeTypeId,
                StartingTime,
                EndingTime,
                OrderNo,
                LeisureCityId,
                LeisureFromTime,
                LeisureToTime,
                WillingForAnotherTripBeforePickUp,
                WillingForAnotherTripAfterDrop,
                DriverId,
                DriverName,
                VehicleCategoryId,
                VehicleBrandId,
                VehicleDetailsId,
                RegistrationNo,
                VehicleVendorName,
                DriverMobile,
                TripDetailedNotes
            )
            VALUES
            (
                @VehicleBookingMasterId,
                1,
                0,
                @ReqStart,
                @FromCityId,
                @ToCityId,
                LEFT(@PickupLocation, 150),
                LEFT(@DropLocation, 150),
                1,
                CONVERT(VARCHAR(5), @PickupDateTime, 108),
                CONVERT(VARCHAR(5), @ReturnDateTime, 108),
                1,
                NULL,
                NULL,
                NULL,
                NULL,
                NULL,
                0,
                '',
                @VehicleCategoryId,
                @VehicleBrandId,
                @VehicleDetailsId,
                ISNULL(@RegistrationNo, ''),
                ISNULL(@VendorName, ''),
                '',
                NULL
            );

            /*=====================================================
              12. INSERT TAXHIBE BOOKINGS
            =====================================================*/

            INSERT INTO dbo.TaxHiBEBookings
            (
                ClientRequestId,
                BookingNo,
                VehicleBookingMasterId,
                UserId,
                BookingStatus,
                HoldExpiresAtUtc,
                CreatedDateUtc,
                ModifiedDateUtc,
                Name,
                PhoneNumber,
                Email,
                AlternateEmail,
                HasGST,
                GSTNumber,
                GSTCompanyName,
                TripType,
                FromCityId,
                ToCityId,
                Route,
                PickupDateTime,
                ReturnDateTime,
                DropDate,
                PickupLocation,
                DropLocation,
                VendorId,
                VehicleId,
                VehicleDetailsId,
                VehicleCategoryId,
                VehicleBrandId,
                VehicleName,
                FuelType,
                PaymentOption,
                CouponCode,
                DiscountAmount,
                BaseFare,
                DriverAllowance,
                AddOnsTotalAmount,
                GSTAmount,
                TotalFare,
                PayableNowAmount,
                BalancePayableAmount
            )
            VALUES
            (
                @ClientRequestId,
                @BookingNo,
                @VehicleBookingMasterId,
                @UserId,
                'Pending',
                DATEADD(MINUTE, @HoldMinutes, @Now),
                @Now,
                @Now,
                @Name,
                @PhoneNumber,
                @Email,
                @AlternateEmail,
                @HasGST,
                @GSTNumber,
                @GSTCompanyName,
                @TripType,
                @FromCityId,
                @ToCityId,
                @Route,
                @PickupDateTime,
                @ReturnDateTime,
                @DropDate,
                @PickupLocation,
                @DropLocation,
                @VendorId,
                @VehicleId,
                @VehicleDetailsId,
                @VehicleCategoryId,
                @VehicleBrandId,
                @VehicleName,
                @FuelType,
                @PaymentOption,
                @CouponCode,
                @DiscountAmount,
                @BaseFare,
                @DriverAllowance,
                @AddOnsTotalAmount,
                @GSTAmount,
                @CalcTotal,
                @CalcPayNow,
                @CalcTotal - @CalcPayNow
            );

            SET @BookingId =
                CAST(SCOPE_IDENTITY() AS INT);

            /*=====================================================
              13. INSERT BOOKING ADD-ONS
            =====================================================*/

            IF @AddOns IS NOT NULL
            BEGIN

                INSERT INTO dbo.TaxHiBEBookingAddOns
                (
                    BookingId,
                    AddOnId,
                    AddOnName,
                    PriceType,
                    UnitPrice,
                    CalculatedAmount
                )
                SELECT
                    @BookingId,
                    A.AddOn.value('(AddOnId/text())[1]', 'INT'),
                    A.AddOn.value('(AddOnName/text())[1]', 'NVARCHAR(200)'),
                    A.AddOn.value('(PriceType/text())[1]', 'VARCHAR(30)'),
                    A.AddOn.value('(UnitPrice/text())[1]', 'DECIMAL(18,2)'),
                    A.AddOn.value('(CalculatedAmount/text())[1]', 'DECIMAL(18,2)')
                FROM @AddOns.nodes('/AddOns/AddOn') A(AddOn);

            END;

            /*=====================================================
              14. INSERT BOOKING PAYMENT
            =====================================================*/

            INSERT INTO dbo.TaxHiBEBookingPayments
            (
                BookingId,
                PaymentAmount,
                PaymentOption,
                PaymentStatus
            )
            VALUES
            (
                @BookingId,
                @CalcPayNow,
                @PaymentOption,
                'Pending'
            );

        END;

        /*=========================================================
          15. COMMIT TRANSACTION
        =========================================================*/

        COMMIT TRANSACTION;

        /*=========================================================
          16. RETURN BOOKING RESPONSE
        =========================================================*/

        SELECT
            B.BookingId,
            B.BookingNo,
            P.BookingPaymentId,
            B.UserId,
            B.BookingStatus,
            P.PaymentStatus,
            B.HoldExpiresAtUtc,
            B.TotalFare,
            B.PayableNowAmount,
            B.BalancePayableAmount,
            CAST(
                CASE
                    WHEN @ExistingBookingId IS NULL THEN 0
                    ELSE 1
                END AS BIT
            ) AS IsDuplicateRequest
        FROM dbo.TaxHiBEBookings B
        OUTER APPLY
        (
            SELECT TOP (1)
                BookingPaymentId,
                PaymentStatus
            FROM dbo.TaxHiBEBookingPayments
            WHERE BookingId = B.BookingId
            ORDER BY BookingPaymentId DESC
        ) P
        WHERE B.BookingId = ISNULL(
            @ExistingBookingId,
            @BookingId
        );

    END TRY

    BEGIN CATCH

        DECLARE @ErrNo INT = ERROR_NUMBER();
        DECLARE @ErrMsg NVARCHAR(2048) = ERROR_MESSAGE();

        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        /*=========================================================
          17. HANDLE DUPLICATE CLIENT REQUEST
        =========================================================*/

        IF @ErrNo IN (2601, 2627)
        BEGIN

            SELECT
                @ExistingBookingId = BookingId
            FROM dbo.TaxHiBEBookings
            WHERE ClientRequestId = @ClientRequestId;

            IF @ExistingBookingId IS NOT NULL
            BEGIN

                SELECT
                    B.BookingId,
                    B.BookingNo,
                    P.BookingPaymentId,
                    B.UserId,
                    B.BookingStatus,
                    P.PaymentStatus,
                    B.HoldExpiresAtUtc,
                    B.TotalFare,
                    B.PayableNowAmount,
                    B.BalancePayableAmount,
                    CAST(1 AS BIT) AS IsDuplicateRequest
                FROM dbo.TaxHiBEBookings B
                OUTER APPLY
                (
                    SELECT TOP (1)
                        BookingPaymentId,
                        PaymentStatus
                    FROM dbo.TaxHiBEBookingPayments
                    WHERE BookingId = B.BookingId
                    ORDER BY BookingPaymentId DESC
                ) P
                WHERE B.BookingId = @ExistingBookingId;

                RETURN;

            END;

        END;

        THROW;

    END CATCH;

END;


GO
